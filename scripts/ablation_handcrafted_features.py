"""Phase 1 ablation — run once the real sweep has completed.

    docker compose run app python -m scripts.ablation_handcrafted_features

Answers one question: is the 384-dim embedding half of the router's input
pulling its weight, or would 9 hand-crafted numbers alone do just as well?

Trains a second router using only hand-crafted features (see
src/eval/ablation.py for the full reasoning) and compares it to the
original combined-feature router's already-logged confidence scores —
both scored with the identical brier_score/discrimination_auc/
calibration_table functions used in scripts/analyze_phase1.py.

Zero new API calls: every input already exists in Supabase from the real
sweep (scripts/run_phase1_sweep.py). This script only reads.

Writes PHASE1_ABLATION_FINDINGS.md — a separate file from
PHASE1_FINDINGS.md, so this doesn't clobber the original router's writeup.
"""

from __future__ import annotations

from dotenv import load_dotenv

load_dotenv()

from src.db.supabase_client import SupabaseLogger  # noqa: E402
from src.eval.ablation import (  # noqa: E402
    cheap_records_by_task,
    compare,
    original_confidence_by_task,
    predict_confidence_by_task,
    train_handcrafted_only_router,
)

logger = SupabaseLogger()

print("Fetching results from Supabase...")
train_rows = logger.fetch_by_phase("router_training_baseline")
cheap_rows = logger.fetch_by_phase("router_baseline_cheap")
cascade_rows = logger.fetch_by_phase("router_cascade")

if not train_rows or not cheap_rows or not cascade_rows:
    raise SystemExit(
        "Missing results for one or more phases — run scripts/run_phase1_sweep.py "
        "to completion first. This ablation reuses that sweep's data; it doesn't "
        "make any new API calls of its own."
    )

print(f"Training hand-crafted-only router on {len(train_rows)} training-split rows...")
handcrafted_router = train_handcrafted_only_router(train_rows)

print(f"Scoring both routers against {len(cheap_rows)} test-split rows...")
cheap_by_task = cheap_records_by_task(cheap_rows)
original_confidence = original_confidence_by_task(cascade_rows)
handcrafted_confidence = predict_confidence_by_task(handcrafted_router, cheap_rows)

result = compare(cheap_by_task, original_confidence, handcrafted_confidence)

print("\n--- Original router (393 raw features: 384-dim embedding + 9 hand-crafted, no PCA) ---")
print(f"Brier score: {result.original_brier:.4f}")
print(f"Discrimination AUC: {result.original_auc:.4f}")

print("\n--- Hand-crafted-only router (9 features, no embedding) ---")
print(f"Brier score: {result.handcrafted_brier:.4f}")
print(f"Discrimination AUC: {result.handcrafted_auc:.4f}")

auc_delta = result.handcrafted_auc - result.original_auc
print(f"\nAUC delta (hand-crafted-only minus original): {auc_delta:+.4f}")
if auc_delta < -0.03:
    verdict = (
        "Hand-crafted-only is meaningfully worse — the embedding was carrying real "
        "signal. Worth investigating whether PCA (never actually tested in a real "
        "sweep) or a different reduction would preserve more of it."
    )
elif auc_delta > 0.03:
    verdict = (
        "Hand-crafted-only is meaningfully better — the embedding wasn't helping "
        "for this benchmark, at least not the way it was fed to the classifier here."
    )
else:
    verdict = (
        "The two are within noise of each other. This does NOT prove the embedding "
        "is useless — only that concatenating it with hand-crafted features and "
        "feeding both into this classifier isn't extracting extra signal from it. "
        "Raw embeddings alone (no hand-crafted features, no PCA) haven't been "
        "tested and remain a genuinely open comparison."
    )
print(f"\n{verdict}")


def _calibration_table_md(buckets) -> str:
    return "\n".join(
        f"| [{b.range_low:.2f}-{b.range_high:.2f}) | {b.n_tasks} | "
        f"{b.mean_predicted_confidence:.2f} | {b.empirical_accuracy:.2f} |"
        for b in buckets
    )


findings_md = f"""# Phase 1 Ablation Findings — Hand-crafted features only

Generated by `scripts/ablation_handcrafted_features.py`. Reuses data already
logged to Supabase by the real Phase 1 sweep — no new API calls were made
to produce this file.

**Question:** the original router trains on 393 raw columns (384-dim
embedding + 9 hand-crafted features, no PCA — PCA exists in `classifier.py`
but has not yet been exercised in a real sweep). Is the embedding half
actually contributing, or would the 9 hand-crafted numbers alone do just
as well?

## Original router (393 features: embedding + hand-crafted, no reduction)

- **Brier score:** {result.original_brier:.4f}
- **Discrimination AUC:** {result.original_auc:.4f}

| Confidence bucket | n tasks | Mean predicted | Actual accuracy |
|---|---|---|---|
{_calibration_table_md(result.original_calibration)}

## Hand-crafted-only router (9 features, no embedding)

- **Brier score:** {result.handcrafted_brier:.4f}
- **Discrimination AUC:** {result.handcrafted_auc:.4f}

| Confidence bucket | n tasks | Mean predicted | Actual accuracy |
|---|---|---|---|
{_calibration_table_md(result.handcrafted_calibration)}

## Verdict

AUC delta (hand-crafted-only minus original): {auc_delta:+.4f}

{verdict}

**What this does and doesn't tell us:** this isolates "embedding + hand-crafted,
concatenated, no reduction" vs. "hand-crafted alone." It does not test raw
embeddings alone, and it does not test PCA (never run in a real sweep to
date) — so a middling result here shouldn't be read as "embeddings are
useless." See `PROGRESS.md`'s Open Questions for the follow-up this points to.
"""

with open("PHASE1_ABLATION_FINDINGS.md", "w") as f:
    f.write(findings_md)

print("\nWrote PHASE1_ABLATION_FINDINGS.md")